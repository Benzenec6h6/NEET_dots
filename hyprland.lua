-- 初回起動の警告バナーを無効化
-- (Lua設定では明示しない場合でも警告は出ませんが、無効化を指定する場合は以下のように書けます)
hl.config({
    autogenerated = false,
})

-- ディスプレイ設定 (自動認識)
-- monitor = , preferred, auto, 1 に対応
hl.monitor({
    output = "",
    mode = "preferred",
    position = "auto",
    scale = 1,
})

-- VM環境向け: ハードウェアカーソルを無効化 (マウス消失防止)
hl.config({
    cursor = {
        no_hardware_cursors = true,
    },
})

-- 修飾キー: Super
local mainMod = "SUPER"

-- ターミナル起動 (Super + Enter)
hl.bind(mainMod .. " + RETURN", hl.dsp.exec_cmd("kitty"))

-- 終了 (Super + M)
hl.bind(mainMod .. " + M", hl.dsp.exit())
